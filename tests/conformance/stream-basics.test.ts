// Conformance: stream factories, single-use rule, BaseStream (flags, iterator, close handlers).
// Expectations come from the reference docs for Stream / BaseStream / package summary.
import { ArrayList, IntStream, Spliterator, Stream, StreamSupport } from '../../src';
import { expectThrows } from '../helpers';

const ISE = 'IllegalStateException';

describe('Stream factories', () => {
  it('of(values) streams the values in order', () => expect(Stream.of(1, 2, 3).toArray()).toEqual([1, 2, 3]));
  it('of() with no values is empty', () => expect(Stream.of().count()).toBe(0));
  it('of(single) has one element', () => expect(Stream.of('a').toArray()).toEqual(['a']));
  it('of allows null elements', () => expect(Stream.of<string | null>('a', null).toArray()).toEqual(['a', null]));
  it('empty() has no elements', () => expect(Stream.empty<number>().toArray()).toEqual([]));
  it('empty().findFirst() is empty', () => expect(Stream.empty().findFirst().isPresent()).toBe(false));

  // "Returns a sequential Stream containing a single element, if non-null, otherwise returns an empty Stream."
  it('ofNullable(non-null) has one element', () => expect(Stream.ofNullable('x').toArray()).toEqual(['x']));
  it('ofNullable(null) is empty', () => expect(Stream.ofNullable<string>(null).count()).toBe(0));
  it('ofNullable(undefined) is empty (undefined counts as null)', () => expect(Stream.ofNullable<string>(undefined).count()).toBe(0));

  describe('iterate(seed, f)', () => {
    // "The first element (position 0) in the Stream will be the provided seed. For n > 0, the element at
    // position n, will be the result of applying the function f to the element at position n - 1."
    it('starts with the seed then applies f repeatedly', () =>
      expect(Stream.iterate(1, (x) => x * 2).limit(5).toArray()).toEqual([1, 2, 4, 8, 16]));
    it('is infinite but short-circuits with findFirst', () => expect(Stream.iterate(7, (x) => x + 1).findFirst().get()).toBe(7));
    it('f receives the previous element', () => {
      const seen: number[] = [];
      Stream.iterate(0, (x) => {
        seen.push(x);
        return x + 3;
      })
        .limit(4)
        .toArray();
      expect(seen.slice(0, 3)).toEqual([0, 3, 6]);
    });
    it('can be combined with skip', () => expect(Stream.iterate(0, (x) => x + 1).skip(5).limit(3).toArray()).toEqual([5, 6, 7]));
    it('allows a null seed', () =>
      expect(Stream.iterate<string | null>(null, (x) => (x === null ? 'a' : x + 'a')).limit(3).toArray()).toEqual([null, 'a', 'aa']));
  });

  describe('iterate(seed, hasNext, next)', () => {
    // Doc example: Stream.iterate(1, n -> n < 10, n -> n + 1) behaves like for (n = 1; n < 10; n++)
    it('behaves like a for loop', () =>
      expect(Stream.iterate(1, (n) => n < 10, (n) => n + 1).toArray()).toEqual([1, 2, 3, 4, 5, 6, 7, 8, 9]));
    // "The stream terminates as soon as the hasNext predicate returns false."
    it('is empty when the seed fails hasNext', () => expect(Stream.iterate(10, (n) => n < 10, (n) => n + 1).count()).toBe(0));
    it('does not call next after hasNext fails', () => {
      const nexts: number[] = [];
      Stream.iterate(
        1,
        (n) => n <= 3,
        (n) => {
          nexts.push(n);
          return n + 1;
        },
      ).forEach(() => {});
      expect(nexts).toEqual([1, 2, 3]);
    });
    it('hasNext is applied to the seed and every generated value', () => {
      const tested: number[] = [];
      Stream.iterate(
        0,
        (n) => {
          tested.push(n);
          return n < 2;
        },
        (n) => n + 1,
      ).toArray();
      expect(tested).toEqual([0, 1, 2]);
    });
    it('works on strings', () =>
      expect(Stream.iterate('a', (s) => s.length <= 3, (s) => s + 'b').toArray()).toEqual(['a', 'ab', 'abb']));
  });

  describe('generate(s)', () => {
    // "Returns an infinite sequential unordered stream where each element is generated by the provided Supplier."
    it('produces supplier values, limited', () => expect(Stream.generate(() => 1).limit(3).toArray()).toEqual([1, 1, 1]));
    it('calls the supplier per element', () => {
      let i = 0;
      expect(Stream.generate(() => i++).limit(4).toArray()).toEqual([0, 1, 2, 3]);
    });
    it('anyMatch short-circuits on an infinite generated stream', () => {
      let i = 0;
      expect(Stream.generate(() => i++).anyMatch((x) => x === 5)).toBe(true);
    });
  });

  describe('concat(a, b)', () => {
    // "...whose elements are all the elements of the first stream followed by all the elements of the second stream."
    it('first then second', () => expect(Stream.concat(Stream.of(1, 2), Stream.of(3, 4)).toArray()).toEqual([1, 2, 3, 4]));
    it('with empty first', () => expect(Stream.concat(Stream.empty<number>(), Stream.of(3)).toArray()).toEqual([3]));
    it('with empty second', () => expect(Stream.concat(Stream.of(1), Stream.empty<number>()).toArray()).toEqual([1]));
    it('both empty', () => expect(Stream.concat(Stream.empty(), Stream.empty()).count()).toBe(0));
    it('nested concat keeps order', () =>
      expect(Stream.concat(Stream.concat(Stream.of(1), Stream.of(2)), Stream.concat(Stream.of(3), Stream.of(4))).toArray()).toEqual([1, 2, 3, 4]));
    // "Creates a lazily concatenated stream"
    it('is lazy: nothing from the inputs runs before the terminal op', () => {
      const log: string[] = [];
      const c = Stream.concat(
        Stream.of(1).peek(() => log.push('a')),
        Stream.of(2).peek(() => log.push('b')),
      );
      expect(log).toEqual([]);
      c.toArray();
      expect(log).toEqual(['a', 'b']);
    });
    it('short-circuits: the second (infinite) stream is not drained', () =>
      expect(Stream.concat(Stream.of(0), Stream.iterate(1, (x) => x + 1)).limit(4).toArray()).toEqual([0, 1, 2, 3]));
    it('works when the first stream is infinite and limited', () =>
      expect(Stream.concat(Stream.generate(() => 'x'), Stream.of('y')).limit(2).toArray()).toEqual(['x', 'x']));
    // "When the resulting stream is closed, the close handlers for both input streams are invoked."
    it('closing the result closes both inputs, first then second', () => {
      const log: string[] = [];
      const c = Stream.concat(Stream.of(1).onClose(() => log.push('a')), Stream.of(2).onClose(() => log.push('b')));
      c.close();
      expect(log).toEqual(['a', 'b']);
    });
    // "...and parallel if either of the input streams is parallel."
    it('is parallel if either input is parallel', () => {
      expect(Stream.concat(Stream.of(1).parallel(), Stream.of(2)).isParallel()).toBe(true);
      expect(Stream.concat(Stream.of(1), Stream.of(2).parallel()).isParallel()).toBe(true);
    });
    it('is sequential if both inputs are sequential', () => expect(Stream.concat(Stream.of(1), Stream.of(2)).isParallel()).toBe(false));
    // "This method operates on the two input streams" — the inputs are consumed.
    it('the input streams cannot be reused afterwards', () => {
      const a = Stream.of(1);
      const b = Stream.of(2);
      Stream.concat(a, b);
      expectThrows(() => a.toArray(), ISE);
      expectThrows(() => b.toArray(), ISE);
    });
    it('null argument throws NullPointerException', () => expectThrows(() => Stream.concat(null as any, Stream.of(1)), 'NullPointerException'));
  });

  describe('builder()', () => {
    it('add chains and build streams in order', () => expect(Stream.builder<number>().add(1).add(2).add(3).build().toArray()).toEqual([1, 2, 3]));
    it('accept adds elements', () => {
      const b = Stream.builder<string>();
      b.accept('x');
      b.accept('y');
      expect(b.build().toArray()).toEqual(['x', 'y']);
    });
    it('empty builder builds an empty stream', () => expect(Stream.builder().build().count()).toBe(0));
    it('builder accepts null', () => expect(Stream.builder<string | null>().add(null).build().toArray()).toEqual([null]));
    // "IllegalStateException - if the builder has already transitioned to the built state"
    it('accept after build throws IllegalStateException', () => {
      const b = Stream.builder<number>();
      b.build();
      expectThrows(() => b.accept(1), ISE);
    });
    it('add after build throws IllegalStateException', () => {
      const b = Stream.builder<number>();
      b.build();
      expectThrows(() => b.add(1), ISE);
    });
    it('build twice throws IllegalStateException', () => {
      const b = Stream.builder<number>();
      b.build();
      expectThrows(() => b.build(), ISE);
    });
  });
});

describe('Single use: "A stream should be operated on ... only once" (library: reuse throws IllegalStateException)', () => {
  const terminals: [string, (s: Stream<number>) => unknown][] = [
    ['toArray', (s) => s.toArray()],
    ['forEach', (s) => s.forEach(() => {})],
    ['count', (s) => s.count()],
    ['collect', (s) => s.collect(() => [] as number[], (a, x) => a.push(x), (a, b) => a.push(...b))],
    ['reduce', (s) => s.reduce(0, (a, b) => a + b)],
    ['findFirst', (s) => s.findFirst()],
    ['anyMatch', (s) => s.anyMatch((x) => x > 0)],
    ['iterator', (s) => s.iterator()],
    ['spliterator', (s) => s.spliterator()],
    ['toList', (s) => s.toList()],
    ['map', (s) => s.map((x) => x)],
    ['filter', (s) => s.filter(() => true)],
    ['limit', (s) => s.limit(1)],
    ['sorted', (s) => s.sorted()],
  ];
  it.each(terminals)('second terminal op after %s throws', (_name, op) => {
    const s = Stream.of(1, 2, 3);
    op(s);
    expectThrows(() => s.toArray(), ISE);
  });
  it.each(terminals)('second intermediate op after %s throws', (_name, op) => {
    const s = Stream.of(1, 2, 3);
    op(s);
    expectThrows(() => s.map((x) => x + 1), ISE);
  });
  it('the derived stream is still usable after linking', () => {
    const s = Stream.of(1, 2, 3);
    const m = s.map((x) => x * 10);
    expect(m.toArray()).toEqual([10, 20, 30]);
  });
  it('reuse of a number stream throws', () => {
    const s = IntStream.of(1, 2);
    s.sum();
    expectThrows(() => s.sum(), ISE);
  });
  it('for..of iteration consumes the stream', () => {
    const s = Stream.of(1, 2);
    expect([...s]).toEqual([1, 2]);
    expectThrows(() => s.count(), ISE);
  });
});

describe('BaseStream', () => {
  it('a fresh stream is sequential', () => expect(Stream.of(1).isParallel()).toBe(false));
  it('parallel() sets the flag', () => expect(Stream.of(1).parallel().isParallel()).toBe(true));
  it('sequential() clears the flag', () => expect(Stream.of(1).parallel().sequential().isParallel()).toBe(false));
  it('the last parallel/sequential call wins for the pipeline', () =>
    expect(Stream.of(1, 2).parallel().map((x) => x).sequential().filter(() => true).isParallel()).toBe(false));
  it('parallel results equal sequential results for an ordered source', () =>
    expect(Stream.of(5, 3, 1, 4).parallel().map((x) => x * 2).sorted().toArray()).toEqual([2, 6, 8, 10]));
  it('unordered() keeps the elements', () => expect(Stream.of(3, 1, 2).unordered().sorted().toArray()).toEqual([1, 2, 3]));
  it('parallel reduce with identity matches sequential', () =>
    expect(Stream.of(1, 2, 3, 4, 5).parallel().reduce(0, (a, b) => a + b)).toBe(15));

  describe('iterator()', () => {
    it('iterates in encounter order', () => {
      const it = Stream.of('a', 'b').iterator();
      const out: string[] = [];
      while (it.hasNext()) out.push(it.next());
      expect(out).toEqual(['a', 'b']);
    });
    it('next() past the end throws NoSuchElementException', () => {
      const it = Stream.of(1).iterator();
      it.next();
      expectThrows(() => it.next(), 'NoSuchElementException');
    });
    it('is lazy over an infinite stream', () => {
      const it = Stream.iterate(0, (x) => x + 1).iterator();
      expect([it.next(), it.next(), it.next()]).toEqual([0, 1, 2]);
    });
    it('streams are JS-iterable', () => expect(Array.from(Stream.of(1, 2, 3).map((x) => x + 1))).toEqual([2, 3, 4]));
  });

  describe('spliterator()', () => {
    it('traverses the stream elements', () => {
      const out: number[] = [];
      Stream.of(1, 2, 3).spliterator().forEachRemaining((x) => out.push(x));
      expect(out).toEqual([1, 2, 3]);
    });
    it('tryAdvance returns false when exhausted', () => {
      const sp = Stream.of(9).spliterator();
      expect(sp.tryAdvance(() => {})).toBe(true);
      expect(sp.tryAdvance(() => {})).toBe(false);
    });
    it('round-trips through StreamSupport.stream', () =>
      expect(StreamSupport.stream(Stream.of(1, 2).map((x) => x * 3).spliterator(), false).toArray()).toEqual([3, 6]));
    it('stream of an ArrayList is ORDERED', () =>
      expect(ArrayList.of(1, 2).stream().spliterator().hasCharacteristics(Spliterator.ORDERED)).toBe(true));
  });

  describe('onClose / close', () => {
    // "Close handlers are run when the close() method is called on the stream, and are executed in the order they were added."
    it('handlers run in registration order', () => {
      const log: number[] = [];
      Stream.of(1)
        .onClose(() => log.push(1))
        .onClose(() => log.push(2))
        .onClose(() => log.push(3))
        .close();
      expect(log).toEqual([1, 2, 3]);
    });
    it('handlers do not run on a terminal operation', () => {
      const log: string[] = [];
      Stream.of(1)
        .onClose(() => log.push('closed'))
        .toArray();
      expect(log).toEqual([]);
    });
    it('handlers registered on different pipeline stages all run', () => {
      const log: string[] = [];
      const s = Stream.of(1)
        .onClose(() => log.push('a'))
        .map((x) => x)
        .onClose(() => log.push('b'));
      s.close();
      expect(log).toEqual(['a', 'b']);
    });
    it('close on a stream without handlers is fine', () => expect(() => Stream.of(1).close()).not.toThrow());
    // "All close handlers are run, even if earlier close handlers throw exceptions. If any close handler throws an
    // exception, the first exception thrown will be relayed to the caller of close(), with any remaining exceptions
    // added to that exception as suppressed exceptions"
    it('all handlers run even if one throws, and the first exception is rethrown', () => {
      const log: number[] = [];
      const e1 = new Error('first');
      const s = Stream.of(1)
        .onClose(() => {
          log.push(1);
          throw e1;
        })
        .onClose(() => log.push(2));
      let caught: unknown;
      try {
        s.close();
      } catch (e) {
        caught = e;
      }
      expect(caught).toBe(e1);
      expect(log).toEqual([1, 2]);
    });
    it('later exceptions are attached as suppressed', () => {
      const e1 = new Error('first');
      const e2 = new Error('second');
      const e3 = new Error('third');
      const s = Stream.of(1)
        .onClose(() => {
          throw e1;
        })
        .onClose(() => {
          throw e2;
        })
        .onClose(() => {
          throw e3;
        });
      let caught: any;
      try {
        s.close();
      } catch (e) {
        caught = e;
      }
      expect(caught).toBe(e1);
      expect(caught.suppressed).toContain(e2);
      expect(caught.suppressed).toContain(e3);
    });
    // "(unless one of the remaining exceptions is the same exception as the first exception, since an exception cannot suppress itself.)"
    it('the same exception thrown twice does not suppress itself', () => {
      const e1 = new Error('same');
      const s = Stream.of(1)
        .onClose(() => {
          throw e1;
        })
        .onClose(() => {
          throw e1;
        });
      let caught: any;
      try {
        s.close();
      } catch (e) {
        caught = e;
      }
      expect(caught).toBe(e1);
      expect(caught.suppressed ?? []).not.toContain(e1);
    });
    it('close handlers on a number stream', () => {
      const log: string[] = [];
      IntStream.range(0, 3)
        .onClose(() => log.push('x'))
        .close();
      expect(log).toEqual(['x']);
    });
    it('onClose with null throws NullPointerException', () => expectThrows(() => Stream.of(1).onClose(null as any), 'NullPointerException'));
  });
});

describe('Null arguments to Stream operations throw NullPointerException', () => {
  const NPE = 'NullPointerException';
  const ops: [string, (s: Stream<number>) => unknown][] = [
    ['filter', (s) => s.filter(null as any)],
    ['map', (s) => s.map(null as any)],
    ['flatMap', (s) => s.flatMap(null as any)],
    ['peek', (s) => s.peek(null as any)],
    ['forEach', (s) => s.forEach(null as any)],
    ['anyMatch', (s) => s.anyMatch(null as any)],
    ['min', (s) => s.min(null as any)],
    ['collect', (s) => s.collect(null as any)],
    ['takeWhile', (s) => s.takeWhile(null as any)],
    ['gather', (s) => s.gather(null as any)],
  ];
  // Eagerly or at the latest when the terminal operation runs.
  it.each(ops)('%s(null)', (_n, op) =>
    expectThrows(() => {
      const r = op(Stream.of(1, 2)) as any;
      if (r && typeof r.toArray === 'function') r.toArray();
    }, NPE));
});
